window.I18N_FR = I18N_FR;
window.I18N_IT = I18N_IT;
window.I18N_DE = I18N_DE;
window.I18N_ES = I18N_ES;
window.I18N_NL = I18N_NL;
window.I18N_PT = I18N_PT;
window.i18n = {
  t: t,
  translateDOM: translateDOM,
  currentLang: 'en',
  languages: ['en', 'fr', 'it', 'de', 'es', 'nl', 'pt'],
  dictionaries: DICTIONARIES,
  dictionary: I18N_EN,
  dict: I18N_EN,
  getLanguage: function () {
    return window.i18n.currentLang;
  },
  setLanguage: function (lang) {
    if (!DICTIONARIES[lang]) return;
    window.i18n.currentLang = lang;
    window.i18n.dictionary = DICTIONARIES[lang];
    window.i18n.dict = DICTIONARIES[lang];
    if (typeof document !== 'undefined') {
      if (document.documentElement) {
        document.documentElement.lang = lang;
      }
      translateDOM(document, lang);
    }
    if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
      window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: lang } }));
    }
  }
};
window.I18n = window.i18n;
