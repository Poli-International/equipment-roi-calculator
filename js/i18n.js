/**
 * Universal translation function.
 * Returns translated string with parameter replacements.
 * Automatically injects the active currency symbol if {curr} is unsupplied.
 *
 * @param {string} key
 * @param {Object} [params]
 * @param {string} [lang]
 * @returns {string}
 */
function t(key, params, lang) {
  var activeLang = lang || (typeof window !== 'undefined' && window.i18n && window.i18n.currentLang) || (typeof document !== 'undefined' && document.documentElement && document.documentElement.lang) || 'en';
  var activeDict = DICTIONARIES[activeLang] || I18N_EN;
  var str = (activeDict && activeDict[key] !== undefined)
    ? activeDict[key]
    : (I18N_EN[key] !== undefined ? I18N_EN[key] : key);
  var currentSymbol = (typeof window !== 'undefined' && window.getCurrencySymbol && typeof window.getCurrencySymbol === 'function')
    ? window.getCurrencySymbol()
    : '£';
  var mergedParams = Object.assign({ curr: currentSymbol }, params || {});
  for (var p in mergedParams) {
    if (Object.prototype.hasOwnProperty.call(mergedParams, p)) {
      str = str.replace(new RegExp('\{' + p + '\}', 'g'), String(mergedParams[p]));
    }
  }
  return str;
}

/**
 * Translates all translatable DOM elements and attributes across a root container.
 *
 * @param {HTMLElement|Document} [root]
 * @param {string} [lang]
 */
function translateDOM(root, lang) {
  var el = root || document;
  if (!el || !el.querySelectorAll) return;
  var activeLang = lang || (typeof window !== 'undefined' && window.i18n && window.i18n.currentLang) || (typeof document !== 'undefined' && document.documentElement && document.documentElement.lang) || 'en';
  var activeDict = DICTIONARIES[activeLang] || I18N_EN;

  // Text content
  var textNodes = el.querySelectorAll('[data-i18n]');
  for (var i = 0; i < textNodes.length; i++) {
    var node = textNodes[i];
    var k = node.getAttribute('data-i18n');
    if (k && activeDict[k] !== undefined) {
      node.textContent = t(k, null, activeLang);
    }
  }

  // HTML content (for elements containing nested markup)
  var htmlNodes = el.querySelectorAll('[data-i18n-html]');
  for (var h = 0; h < htmlNodes.length; h++) {
    var hNode = htmlNodes[h];
    var hk = hNode.getAttribute('data-i18n-html');
    if (hk && activeDict[hk] !== undefined) {
      hNode.innerHTML = t(hk, null, activeLang);
    }
  }

  // Placeholders
  var placeholders = el.querySelectorAll('[data-i18n-placeholder]');
  for (var p = 0; p < placeholders.length; p++) {
    var pNode = placeholders[p];
    var pk = pNode.getAttribute('data-i18n-placeholder');
    if (pk && activeDict[pk] !== undefined) {
      pNode.setAttribute('placeholder', t(pk, null, activeLang));
    }
  }

  // Aria labels
  var arias = el.querySelectorAll('[data-i18n-aria-label]');
  for (var a = 0; a < arias.length; a++) {
    var aNode = arias[a];
    var ak = aNode.getAttribute('data-i18n-aria-label');
    if (ak && activeDict[ak] !== undefined) {
      aNode.setAttribute('aria-label', t(ak, null, activeLang));
    }
  }

  // Titles
  var titles = el.querySelectorAll('[data-i18n-title]');
  for (var ti = 0; ti < titles.length; ti++) {
    var tNode = titles[ti];
    var tk = tNode.getAttribute('data-i18n-title');
    if (tk && activeDict[tk] !== undefined) {
      tNode.setAttribute('title', t(tk, null, activeLang));
    }
  }

  // Meta tag descriptions / content
  var contents = el.querySelectorAll('[data-i18n-content]');
  for (var c = 0; c < contents.length; c++) {
    var cNode = contents[c];
    var ck = cNode.getAttribute('data-i18n-content');
    if (ck && activeDict[ck] !== undefined) {
      cNode.setAttribute('content', t(ck, null, activeLang));
    }
  }
}

// Auto-run translation on document ready
if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () {
      translateDOM();
    });
  } else {
    translateDOM();
  }
}

